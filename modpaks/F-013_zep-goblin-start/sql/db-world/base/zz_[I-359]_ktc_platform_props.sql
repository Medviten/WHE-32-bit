-- =============================================================================
-- I-359  KTC Oil Platform prop set — un-stack the phase-collapsed twins
--
-- Symptom: the Platform Control Panel cannot be activated, so quest 25204
-- "Release the Valves" cannot be handed in and 25207 "Good-bye, Sweet Oil"
-- cannot be picked up.
--
-- Cause: retail keeps TWO copies of each platform prop in DIFFERENT phases — an
-- interactive one and an inert decorative twin of the same model:
--
--   202613 Platform Control Panel  type 2  QUESTGIVER  tdb434 PhaseId 184
--   205064 Platform Control Panel  type 5  GENERIC     tdb434 PhaseId 179
--   205061 Big Red Button          type 10 GOOBER      tdb434 PhaseId 184
--   205065 Big Red Button          type 5  GENERIC     tdb434 PhaseId 179
--
-- The Neltharion dump gives all four `phaseMask` 50176, and gameobjects.py copies
-- that verbatim, so both copies of each prop spawn in the same phase at byte-
-- identical coordinates with the same displayId. `GameObject::Use` has no case for
-- GAMEOBJECT_TYPE_GENERIC (the switch covers types 0,1,2,6,7,10,13,17), so when the
-- client picks the GENERIC twin under the cursor, clicking does nothing at all.
--
-- PhaseId -> phaseMask derived the documented way, from entries that live in exactly
-- one tdb434 phase and the mask Neltharion gave them:
--   PhaseId 184 -> 50176 (10 single-phase entries agree)  = keep
--   PhaseId 179 ->  8192 ( 9 single-phase entries agree)  = the inert twins
--
-- Also repairs the identity-quaternion defect on all four (see this note's main
-- section): rotation0..3 = 0,0,0,1 is a VALID unit quaternion, so AzerothCore uses
-- it verbatim and never reads `orientation` — these props render at 0 rad instead
-- of the ~177 deg their data claims.
--
-- Separate from zz_[I-359]_valve_rotation.sql on purpose: that file is generated by
-- `zep world edits emit` and is overwritten on every re-emit.
-- =============================================================================

-- Inert decorative twins -> their own phase, so they stop shadowing the
-- interactive props players must click.
UPDATE `gameobject` SET
  `phaseMask` = 8192,
  `rotation2` = 0.999657,
  `rotation3` = 0.026193
WHERE `guid` = 6000831;   -- 205064 Platform Control Panel (GENERIC twin)

UPDATE `gameobject` SET
  `phaseMask` = 8192,
  `rotation2` = 0.999848,
  `rotation3` = 0.017445
WHERE `guid` = 6000832;   -- 205065 Big Red Button (GENERIC twin)

-- Interactive props keep phaseMask 50176; rotation repaired only.
UPDATE `gameobject` SET
  `rotation2` = 0.999657,
  `rotation3` = 0.026193
WHERE `guid` = 6000623;   -- 202613 Platform Control Panel (QUESTGIVER)

UPDATE `gameobject` SET
  `rotation2` = 0.999848,
  `rotation3` = 0.017445
WHERE `guid` = 6000830;   -- 205061 Big Red Button (GOOBER, quest 25207)
