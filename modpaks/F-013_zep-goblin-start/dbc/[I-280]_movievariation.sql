-- ============================================================
-- I-280  MovieVariation.dbc — the missing half of the goblin cinematic wiring
--
-- A Movie.dbc row alone does NOT make a cinematic playable. The 3.3.5a client
-- loads all three movie tables (strings at 0x658f28/0x658f40/0x658f60 in
-- Wow.exe) and resolves a movie as:
--
--   Movie.dbc(id) -> movie_path        (base name, no resolution suffix)
--   MovieVariation rows WHERE movie_id -> file_data_id
--   MovieFileData(file_data_id)        -> resolution
--   => plays <movie_path>_<resolution>.avi
--
-- Movie 22 had a Movie.dbc row but **no MovieVariation rows**, so the client had
-- no variation to resolve and did nothing -- silent, with no error, exactly the
-- symptom this issue chased for a long time. Every id that ever worked (2, 14,
-- 16) has variation rows; every id that failed (22, and the 900-905 test slots)
-- had none.
--
-- Ids are the authentic 4.3.4 values for movie 22 (MovieVariation 124/125 ->
-- MovieFileData 451827/451828), so this stays aligned with retail. Both ranges
-- are free in our tables (variation ids in use: 3,4,32,33,42,43,61,62,103,104;
-- filedata ids in use: 1,2,21,22,220062,220063,356943,356944).
--
-- Both variations are declared, and both files ship. Cata's 451827 is **1280**,
-- which this client never even looks for (see I-279), so it is pointed at a 1024
-- entry in [I-280]_moviefiledata.sql to match Goblin_1024.avi; 451828 stays 800
-- and matches a Goblin_800.avi generated by `zep build cinematic convert`.
--
-- The full pair matters: every movie that resolves on this client (2, 14, 16)
-- declares BOTH a 1024 and an 800 variation. A 1024-only set was tried first and
-- did not play, so a complete set is the shape the client expects.
-- ============================================================

DELETE FROM `movievariation` WHERE `id` IN (124, 125);
INSERT INTO `movievariation` SET
  `id` = 124,
  `movie_id` = 22,
  `file_data_id` = 451827;
INSERT INTO `movievariation` SET
  `id` = 125,
  `movie_id` = 22,
  `file_data_id` = 451828;
